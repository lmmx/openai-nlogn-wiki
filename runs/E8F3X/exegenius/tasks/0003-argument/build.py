QUOTES = []  # (id, quote, deferred)


def Q(s):
    return {"source": "paper", "quote": s}


def inf(id, claim, quote, frm=None, deferred=False, salient=None, page=None):
    n = {"id": id, "intention": "infer", "claim": claim, "quote": Q(quote), "from": frm or []}
    if deferred:
        n["deferred"] = True
    if salient:
        n["salient"] = salient
    if page:
        n["page"] = page
    QUOTES.append((id, quote, deferred))
    return n


def sh(id, claim, method, motiv, children, page=None, frm=None, adds=None, salient=None):
    text, source, quote = motiv
    m = {"text": text, "source": source}
    if quote:
        m["quote"] = Q(quote)
    n = {"id": id, "intention": "show", "claim": claim, "method": method, "motivation": m,
         "children": children, "from": frm or []}
    if page:
        n["page"] = page
    if adds:
        n["adds"] = [{"symbol": a[0], "name": a[1], "meaning": a[2], "relation": a[3]} for a in adds]
    if salient:
        n["salient"] = salient
    return n


